const catalogs: Record<Language, Record<string, string>> = { ru, en };
let activeLanguage: Language = 'en';

const deviceLanguage = (): Language => {
  const languageCode = getLocales()[0]?.languageCode?.toLowerCase();
  return languageCode?.startsWith('ru') ? 'ru' : 'en';
};

const interpolate = (value: string, params?: Params) => {
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, key: string) => String(params[key] ?? ''));
};

export const translateFor = (language: Language, key: string, params?: Params) =>
  interpolate(catalogs[language][key] ?? catalogs.en[key] ?? key, params);

export const translate = (key: string, params?: Params) =>
  translateFor(activeLanguage, key, params);

const storedContentKeys = [
  'recommendation.reason.strongCounter',
  'recommendation.reason.roleFit',
  'recommendation.reason.meta',
  'recommendation.reason.teamNeed',
  'recommendation.reason.limitedData',
  'recommendation.reason.keyMatchup',
  'recommendation.reason.stableTempo',
  'recommendation.risk.comfort',
  'recommendation.lane.general',
  'recommendation.lane.offline',
  'recommendation.patch.offline',
] as const;

export const localizeStoredText = (
  value: string,
  t: (key: string, params?: Params) => string = translate,
) => {
  if (value.startsWith('i18n:')) {
    const [key, parameter] = value.slice(5).split('|');
    if (!key) return value;
    if (key === 'recommendation.reason.position') {
      return t(key, { position: parameter ?? '' });
    }
    if (key === 'recommendation.lane.rank' || key === 'recommendation.lane.adapted') {
      const rankKey = parameter ? `rank.${parameter}` : 'rank.any';
      return t(key, { rank: t(rankKey) });
    }
    return t(key);
  }

  for (const key of storedContentKeys) {
    if (value === ru[key] || value === en[key]) return t(key);
  }

  const position =
    value.match(/^Подходит на позицию ([1-5])$/)?.[1] ??
    value.match(/^Fits position ([1-5])$/)?.[1];
  if (position) return t('recommendation.reason.position', { position });

  for (const key of ['recommendation.lane.rank', 'recommendation.lane.adapted'] as const) {
    for (const language of ['ru', 'en'] as const) {
      const template = catalogs[language][key];
      const prefix = template?.split('{{rank}}')[0];
      if (!prefix || !value.startsWith(prefix)) continue;
      const rank = value.slice(prefix.length);
      const rankEntry = Object.entries(catalogs[language]).find(
        ([catalogKey, label]) => catalogKey.startsWith('rank.') && label === rank,
      );
      return t(key, { rank: rankEntry ? t(rankEntry[0]) : rank });
    }
  }

  return value;
};

type LocaleContextValue = {
  language: Language;
  locale: 'ru-RU' | 'en-US';
  t: (key: string, params?: Params) => string;
};

const LocaleContext = createContext<LocaleContextValue>({
  language: 'en',
  locale: 'en-US',
  t: (key, params) => translateFor('en', key, params),
});

export function LocaleProvider({ children }: PropsWithChildren) {
  const languageMode = useAppStore((state) => state.languageMode);
  const [systemLanguage, setSystemLanguage] = useState<Language>(deviceLanguage);
  const language = languageMode === 'system' ? systemLanguage : languageMode;
  activeLanguage = language;

  useEffect(() => {
    if (Platform.OS !== 'android') return;
    const subscription = AppState.addEventListener('change', (state) => {
      if (state === 'active') setSystemLanguage(deviceLanguage());
    });
    return () => subscription.remove();
  }, []);

  const t = useCallback(
    (key: string, params?: Params) => translateFor(language, key, params),
    [language],
  );
  const value = useMemo<LocaleContextValue>(
    () => ({ language, locale: language === 'ru' ? 'ru-RU' : 'en-US', t }),
    [language, t],
  );

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export const useTranslation = () => useContext(LocaleContext);
